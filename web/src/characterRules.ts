export const characterRules: CharacterRules[] = details.map((ruleDetails) => {
  const character = characters.find((candidate) => candidate.id === ruleDetails.id);
  if (!character) throw new Error(`Unknown Trouble Brewing character: ${ruleDetails.id}`);
  return {
    ...ruleDetails,
    label: character.label,
    ability: character.abilitySummary,
  };
});

const rulesByCharacterId = new Map(characterRules.map((rules) => [rules.id, rules]));

export function characterRulesFor(characterId?: string): CharacterRules | undefined {
  return characterId ? rulesByCharacterId.get(characterId) : undefined;
}
